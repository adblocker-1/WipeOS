#!/usr/bin/env python3
"""Regenerates gui/app/logo_data.c (the WipeOS logo as RGBA arrays) from docs/images/logo.png.
Usage: python3 tools/gen_logo_data.py   (needs Pillow)"""
import os
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
im = Image.open(os.path.join(root, "docs/images/logo.png")).convert("RGBA")
out = ["/* WipeOS logo (docs/images/logo.png), RGBA8888, generated by tools/gen_logo_data.py */", "#include <stdint.h>"]
for name, sz in (("wipeos_logo_48", 48), ("wipeos_logo_160", 160)):
    data = im.resize((sz, sz), Image.LANCZOS).tobytes()
    out.append(f"const int {name}_size = {sz};")
    out.append(f"const uint8_t {name}[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        out.append(",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
with open(os.path.join(root, "gui/app/logo_data.c"), "w") as f:
    f.write("\n".join(out) + "\n")
