#!/usr/bin/env python3
"""Builds app/lang_<code>.c from i18n/keys.txt and i18n/<code>.txt and checks the translations
(every key present, same printf placeholders in the same order, same number of lines in lists)."""
import os, re, sys
root = os.path.dirname(os.path.abspath(__file__))
LANGS = ["de", "fr", "es", "it", "pt", "nl", "pl", "tr", "ru", "uk"]

def load(name):
    d = {}
    for line in open(os.path.join(root, name), encoding="utf-8"):
        line = line.rstrip("\n")
        if "|" not in line:
            continue
        n, t = line.split("|", 1)
        d[int(n)] = t
    return d

def spec(s):
    return [m for m in re.findall(r"%(?:%|[-0-9.]*(?:llu|lld|d|s|f|c|u))", s) if m != "%%"]

def cstr(s):
    return s.replace('"', '\\"') if '\\"' not in s else s

keys = load("keys.txt")
ok = True
for lang in LANGS:
    tr = load(lang + ".txt")
    out = ['/* generated by i18n/gen.py from i18n/%s.txt - do not edit */' % lang, '#include "app.h"', "", "const tr_pair_t tr_%s[] = {" % lang]
    for n, k in keys.items():
        if n not in tr or not tr[n].strip():
            print(f"{lang}: missing {n}: {k}"); ok = False; continue
        t = tr[n]
        if spec(k) != spec(t):
            print(f"{lang}: placeholders differ in {n}: {k!r} / {t!r}"); ok = False
        if k.count("\\n") != t.count("\\n"):
            print(f"{lang}: line count differs in {n}"); ok = False
        if k.startswith(" ") != t.startswith(" "):
            print(f"{lang}: leading space differs in {n}"); ok = False
        out.append('    {"%s", "%s"},' % (cstr(k), cstr(t)))
    for n in tr:
        if n not in keys:
            print(f"{lang}: unknown number {n}"); ok = False
    out += ["    {0, 0},", "};", ""]
    open(os.path.join(root, "../app/lang_%s.c" % lang), "w", encoding="utf-8").write("\n".join(out))
print("ok" if ok else "ERRORS")
sys.exit(0 if ok else 1)
